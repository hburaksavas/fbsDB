-- Açıklama eklenmeyen diğer alanlar için Türkçe, veri türüne uygun kısa açıklama üretir.
BEGIN
  FOR c IN (
    SELECT x.table_name,x.column_name,x.data_type
    FROM dba_tab_columns x
    WHERE x.owner='INDEMNITY_APP'
      AND NOT EXISTS (
        SELECT 1 FROM dba_col_comments d
        WHERE d.owner=x.owner AND d.table_name=x.table_name AND d.column_name=x.column_name AND d.comments IS NOT NULL
      )
  ) LOOP
    DECLARE v_comment VARCHAR2(500);
    BEGIN
      IF c.column_name LIKE '%_ID' THEN v_comment := 'İlişkili kaydın kimliğini gösterir.';
      ELSIF c.data_type='DATE' OR c.data_type LIKE 'TIMESTAMP%' THEN v_comment := 'İlgili olayın tarih ve saat bilgisini tutar.';
      ELSIF c.column_name LIKE '%AMOUNT%' OR c.column_name LIKE '%BALANCE%' OR c.column_name LIKE '%PRINCIPAL%' OR c.column_name LIKE '%_DUE' OR c.column_name LIKE '%_RATE' THEN v_comment := 'Kredi veya tahsilat sürecine ait finansal tutar ya da oranı tutar.';
      ELSIF c.column_name LIKE '%STATUS%' THEN v_comment := 'Kaydın süreç durumunu gösteren kodu tutar.';
      ELSIF c.column_name LIKE '%CODE%' THEN v_comment := 'Süreçte kullanılan kısa ve tekil kodu tutar.';
      ELSIF c.column_name LIKE '%NAME%' THEN v_comment := 'İlgili kişi, kurum veya öğenin adını tutar.';
      ELSIF c.column_name LIKE '%_NO' OR c.column_name LIKE '%_REF' OR c.column_name LIKE '%REFERENCE%' THEN v_comment := 'İşlem veya dosyanın dış sistemlerde kullanılan numara ya da referansını tutar.';
      ELSIF c.column_name LIKE 'IS_%' OR c.column_name LIKE 'REQUIRES_%' THEN v_comment := 'İşlem özelliğini belirten evet/hayır bilgisini tutar.';
      ELSIF c.column_name LIKE '%NOTE%' OR c.column_name LIKE '%DESCRIPTION%' OR c.column_name LIKE '%REASON%' THEN v_comment := 'İşlemle ilgili açıklama veya not bilgisini tutar.';
      ELSIF c.column_name LIKE '%TYPE%' OR c.column_name LIKE '%CHANNEL%' OR c.column_name LIKE '%ROLE%' THEN v_comment := 'İlgili işlemin türünü veya sınıflandırmasını belirtir.';
      ELSE v_comment := 'Tazmin, kredi veya tahsilat sürecine ait ek bilgiyi tutar.';
      END IF;
      EXECUTE IMMEDIATE 'COMMENT ON COLUMN INDEMNITY_APP.'||c.table_name||'.'||c.column_name||' IS '''||REPLACE(v_comment,'''','''''')||'''';
    END;
  END LOOP;
END;
