-- LOAN_APP: products, applications, underwriting, contracts and repayment schedules.
CREATE TABLE LOAN_APP.LOAN_PRODUCTS (
  LOAN_PRODUCT_ID NUMBER PRIMARY KEY, PRODUCT_CODE VARCHAR2(24) NOT NULL UNIQUE, NAME VARCHAR2(80) NOT NULL,
  CURRENCY_CODE CHAR(3) NOT NULL, MIN_AMOUNT NUMBER(16,2) NOT NULL, MAX_AMOUNT NUMBER(16,2) NOT NULL,
  BASE_RATE NUMBER(7,4) NOT NULL, MAX_TERM_MONTHS NUMBER(4) NOT NULL, STATUS VARCHAR2(16) NOT NULL
);
CREATE TABLE LOAN_APP.LOAN_APPLICATIONS (
  APPLICATION_ID NUMBER PRIMARY KEY, APPLICATION_NO VARCHAR2(24) NOT NULL UNIQUE,
  CUSTOMER_ID NUMBER NOT NULL REFERENCES CUSTOMER_APP.CUSTOMERS(CUSTOMER_ID),
  LOAN_PRODUCT_ID NUMBER NOT NULL REFERENCES LOAN_APP.LOAN_PRODUCTS(LOAN_PRODUCT_ID),
  REQUESTED_AMOUNT NUMBER(16,2) NOT NULL, REQUESTED_TERM_MONTHS NUMBER(4) NOT NULL,
  SUBMITTED_AT DATE NOT NULL, STATUS VARCHAR2(20) NOT NULL
);
CREATE TABLE LOAN_APP.LOAN_APPLICATION_DOCUMENTS (
  APPLICATION_DOCUMENT_ID NUMBER PRIMARY KEY, APPLICATION_ID NUMBER NOT NULL REFERENCES LOAN_APP.LOAN_APPLICATIONS(APPLICATION_ID),
  DOCUMENT_TYPE VARCHAR2(32) NOT NULL, DOCUMENT_REF VARCHAR2(80) NOT NULL UNIQUE, RECEIVED_AT DATE NOT NULL, STATUS VARCHAR2(16) NOT NULL
);
CREATE TABLE LOAN_APP.LOAN_DECISIONS (
  DECISION_ID NUMBER PRIMARY KEY, APPLICATION_ID NUMBER NOT NULL UNIQUE REFERENCES LOAN_APP.LOAN_APPLICATIONS(APPLICATION_ID),
  DECISION VARCHAR2(16) NOT NULL, APPROVED_AMOUNT NUMBER(16,2), APPROVED_RATE NUMBER(7,4), DECIDED_AT DATE NOT NULL, DECIDED_BY VARCHAR2(60)
);
CREATE TABLE LOAN_APP.LOANS (
  LOAN_ID NUMBER PRIMARY KEY, LOAN_NO VARCHAR2(24) NOT NULL UNIQUE,
  APPLICATION_ID NUMBER NOT NULL UNIQUE REFERENCES LOAN_APP.LOAN_APPLICATIONS(APPLICATION_ID),
  CUSTOMER_ID NUMBER NOT NULL REFERENCES CUSTOMER_APP.CUSTOMERS(CUSTOMER_ID),
  LOAN_PRODUCT_ID NUMBER NOT NULL REFERENCES LOAN_APP.LOAN_PRODUCTS(LOAN_PRODUCT_ID),
  DISBURSEMENT_ACCOUNT_ID NUMBER NOT NULL REFERENCES ACCOUNT_APP.ACCOUNTS(ACCOUNT_ID),
  PRINCIPAL NUMBER(16,2) NOT NULL, ANNUAL_RATE NUMBER(7,4) NOT NULL, START_DATE DATE NOT NULL,
  MATURITY_DATE DATE NOT NULL, STATUS VARCHAR2(16) NOT NULL
);
CREATE TABLE LOAN_APP.LOAN_SCHEDULES (
  SCHEDULE_ID NUMBER PRIMARY KEY, LOAN_ID NUMBER NOT NULL REFERENCES LOAN_APP.LOANS(LOAN_ID),
  VERSION_NO NUMBER(4) NOT NULL, GENERATED_AT DATE NOT NULL, PAYMENT_FREQUENCY VARCHAR2(16) NOT NULL,
  CONSTRAINT UQ_LOAN_SCHEDULE_VERSION UNIQUE (LOAN_ID, VERSION_NO)
);
CREATE TABLE LOAN_APP.LOAN_INSTALLMENTS (
  INSTALLMENT_ID NUMBER PRIMARY KEY, SCHEDULE_ID NUMBER NOT NULL REFERENCES LOAN_APP.LOAN_SCHEDULES(SCHEDULE_ID),
  INSTALLMENT_NO NUMBER(4) NOT NULL, DUE_DATE DATE NOT NULL, PRINCIPAL_DUE NUMBER(16,2) NOT NULL,
  INTEREST_DUE NUMBER(16,2) NOT NULL, TOTAL_DUE NUMBER(16,2) NOT NULL, STATUS VARCHAR2(16) NOT NULL,
  CONSTRAINT UQ_SCHEDULE_INSTALLMENT UNIQUE (SCHEDULE_ID, INSTALLMENT_NO)
);
CREATE TABLE LOAN_APP.LOAN_PAYMENTS (
  LOAN_PAYMENT_ID NUMBER PRIMARY KEY, LOAN_ID NUMBER NOT NULL REFERENCES LOAN_APP.LOANS(LOAN_ID),
  INSTALLMENT_ID NUMBER NOT NULL REFERENCES LOAN_APP.LOAN_INSTALLMENTS(INSTALLMENT_ID),
  SOURCE_ACCOUNT_ID NUMBER NOT NULL REFERENCES ACCOUNT_APP.ACCOUNTS(ACCOUNT_ID),
  PAID_AT DATE NOT NULL, AMOUNT NUMBER(16,2) NOT NULL, REFERENCE_NO VARCHAR2(32) NOT NULL UNIQUE, STATUS VARCHAR2(16) NOT NULL
);
CREATE TABLE LOAN_APP.LOAN_COLLATERAL (
  COLLATERAL_ID NUMBER PRIMARY KEY, LOAN_ID NUMBER NOT NULL REFERENCES LOAN_APP.LOANS(LOAN_ID),
  COLLATERAL_TYPE VARCHAR2(24) NOT NULL, DESCRIPTION VARCHAR2(160) NOT NULL, APPRAISED_VALUE NUMBER(16,2) NOT NULL, APPRAISED_AT DATE NOT NULL
);
CREATE TABLE LOAN_APP.LOAN_GUARANTORS (
  LOAN_ID NUMBER NOT NULL REFERENCES LOAN_APP.LOANS(LOAN_ID),
  CUSTOMER_ID NUMBER NOT NULL REFERENCES CUSTOMER_APP.CUSTOMERS(CUSTOMER_ID), GUARANTEE_AMOUNT NUMBER(16,2) NOT NULL,
  SIGNED_AT DATE NOT NULL, CONSTRAINT PK_LOAN_GUARANTORS PRIMARY KEY (LOAN_ID, CUSTOMER_ID)
);
CREATE TABLE LOAN_APP.LOAN_RATE_HISTORY (
  RATE_HISTORY_ID NUMBER PRIMARY KEY, LOAN_ID NUMBER NOT NULL REFERENCES LOAN_APP.LOANS(LOAN_ID),
  ANNUAL_RATE NUMBER(7,4) NOT NULL, EFFECTIVE_FROM DATE NOT NULL, EFFECTIVE_TO DATE, REASON VARCHAR2(100)
);
CREATE TABLE LOAN_APP.LOAN_STATUS_HISTORY (
  STATUS_HISTORY_ID NUMBER PRIMARY KEY, LOAN_ID NUMBER NOT NULL REFERENCES LOAN_APP.LOANS(LOAN_ID),
  OLD_STATUS VARCHAR2(16), NEW_STATUS VARCHAR2(16) NOT NULL, CHANGED_AT TIMESTAMP NOT NULL, CHANGED_BY VARCHAR2(60), NOTE VARCHAR2(160)
);

-- Keep cross-schema exploration read-only while making the whole demo browsable from any schema login.
BEGIN
  FOR t IN (SELECT table_name FROM dba_tables WHERE owner = 'ACCOUNT_APP') LOOP
    EXECUTE IMMEDIATE 'GRANT SELECT ON ACCOUNT_APP.' || t.table_name || ' TO CUSTOMER_APP';
  END LOOP;
  FOR t IN (SELECT table_name FROM dba_tables WHERE owner = 'LOAN_APP') LOOP
    EXECUTE IMMEDIATE 'GRANT SELECT ON LOAN_APP.' || t.table_name || ' TO CUSTOMER_APP, ACCOUNT_APP';
  END LOOP;
END;
