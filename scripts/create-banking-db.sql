-- ACCOUNT_APP: branch network, customer accounts, balances and activity.
CREATE TABLE ACCOUNT_APP.BRANCHES (
  BRANCH_ID NUMBER PRIMARY KEY, BRANCH_CODE VARCHAR2(12) NOT NULL UNIQUE, NAME VARCHAR2(100) NOT NULL,
  CITY VARCHAR2(60) NOT NULL, REGION VARCHAR2(60), STATUS VARCHAR2(16) DEFAULT 'ACTIVE' NOT NULL
);
CREATE TABLE ACCOUNT_APP.ACCOUNT_TYPES (
  ACCOUNT_TYPE_ID NUMBER PRIMARY KEY, CODE VARCHAR2(24) NOT NULL UNIQUE, NAME VARCHAR2(80) NOT NULL,
  CURRENCY_CODE CHAR(3) NOT NULL, ALLOWS_OVERDRAFT CHAR(1) DEFAULT 'N' NOT NULL
);
CREATE TABLE ACCOUNT_APP.ACCOUNTS (
  ACCOUNT_ID NUMBER PRIMARY KEY, ACCOUNT_NO VARCHAR2(24) NOT NULL UNIQUE,
  CUSTOMER_ID NUMBER NOT NULL REFERENCES CUSTOMER_APP.CUSTOMERS(CUSTOMER_ID),
  BRANCH_ID NUMBER NOT NULL REFERENCES ACCOUNT_APP.BRANCHES(BRANCH_ID),
  ACCOUNT_TYPE_ID NUMBER NOT NULL REFERENCES ACCOUNT_APP.ACCOUNT_TYPES(ACCOUNT_TYPE_ID),
  OPENED_AT DATE NOT NULL, STATUS VARCHAR2(16) DEFAULT 'OPEN' NOT NULL
);
CREATE TABLE ACCOUNT_APP.ACCOUNT_OWNERS (
  ACCOUNT_ID NUMBER NOT NULL REFERENCES ACCOUNT_APP.ACCOUNTS(ACCOUNT_ID),
  CUSTOMER_ID NUMBER NOT NULL REFERENCES CUSTOMER_APP.CUSTOMERS(CUSTOMER_ID), OWNER_ROLE VARCHAR2(20) NOT NULL,
  ADDED_AT DATE NOT NULL, CONSTRAINT PK_ACCOUNT_OWNERS PRIMARY KEY (ACCOUNT_ID, CUSTOMER_ID)
);
CREATE TABLE ACCOUNT_APP.ACCOUNT_BALANCES (
  ACCOUNT_ID NUMBER NOT NULL REFERENCES ACCOUNT_APP.ACCOUNTS(ACCOUNT_ID), AS_OF_DATE DATE NOT NULL,
  LEDGER_BALANCE NUMBER(16,2) NOT NULL, AVAILABLE_BALANCE NUMBER(16,2) NOT NULL,
  CONSTRAINT PK_ACCOUNT_BALANCES PRIMARY KEY (ACCOUNT_ID, AS_OF_DATE)
);
CREATE TABLE ACCOUNT_APP.TRANSACTION_TYPES (
  TRANSACTION_TYPE_ID NUMBER PRIMARY KEY, CODE VARCHAR2(24) NOT NULL UNIQUE, NAME VARCHAR2(80) NOT NULL, DIRECTION VARCHAR2(8) NOT NULL
);
CREATE TABLE ACCOUNT_APP.ACCOUNT_TRANSACTIONS (
  TRANSACTION_ID NUMBER PRIMARY KEY, ACCOUNT_ID NUMBER NOT NULL REFERENCES ACCOUNT_APP.ACCOUNTS(ACCOUNT_ID),
  TRANSACTION_TYPE_ID NUMBER NOT NULL REFERENCES ACCOUNT_APP.TRANSACTION_TYPES(TRANSACTION_TYPE_ID),
  POSTED_AT TIMESTAMP NOT NULL, AMOUNT NUMBER(16,2) NOT NULL, CURRENCY_CODE CHAR(3) NOT NULL,
  DESCRIPTION VARCHAR2(160), REFERENCE_NO VARCHAR2(32) NOT NULL UNIQUE, STATUS VARCHAR2(16) NOT NULL
);
CREATE TABLE ACCOUNT_APP.CARDS (
  CARD_ID NUMBER PRIMARY KEY, CARD_TOKEN VARCHAR2(32) NOT NULL UNIQUE,
  ACCOUNT_ID NUMBER NOT NULL REFERENCES ACCOUNT_APP.ACCOUNTS(ACCOUNT_ID),
  CUSTOMER_ID NUMBER NOT NULL REFERENCES CUSTOMER_APP.CUSTOMERS(CUSTOMER_ID), CARD_TYPE VARCHAR2(16) NOT NULL,
  ISSUED_AT DATE NOT NULL, EXPIRES_AT DATE NOT NULL, STATUS VARCHAR2(16) NOT NULL
);
CREATE TABLE ACCOUNT_APP.CARD_TRANSACTIONS (
  CARD_TRANSACTION_ID NUMBER PRIMARY KEY, CARD_ID NUMBER NOT NULL REFERENCES ACCOUNT_APP.CARDS(CARD_ID),
  TRANSACTION_ID NUMBER REFERENCES ACCOUNT_APP.ACCOUNT_TRANSACTIONS(TRANSACTION_ID), MERCHANT VARCHAR2(100) NOT NULL,
  AUTHORIZED_AT TIMESTAMP NOT NULL, AMOUNT NUMBER(14,2) NOT NULL, STATUS VARCHAR2(16) NOT NULL
);
CREATE TABLE ACCOUNT_APP.BENEFICIARIES (
  BENEFICIARY_ID NUMBER PRIMARY KEY, ACCOUNT_ID NUMBER NOT NULL REFERENCES ACCOUNT_APP.ACCOUNTS(ACCOUNT_ID),
  BENEFICIARY_NAME VARCHAR2(100) NOT NULL, IBAN VARCHAR2(34) NOT NULL, BANK_NAME VARCHAR2(100), ADDED_AT DATE NOT NULL, STATUS VARCHAR2(16) NOT NULL
);
CREATE TABLE ACCOUNT_APP.TRANSFERS (
  TRANSFER_ID NUMBER PRIMARY KEY, FROM_ACCOUNT_ID NUMBER NOT NULL REFERENCES ACCOUNT_APP.ACCOUNTS(ACCOUNT_ID),
  TO_ACCOUNT_ID NUMBER REFERENCES ACCOUNT_APP.ACCOUNTS(ACCOUNT_ID), BENEFICIARY_ID NUMBER REFERENCES ACCOUNT_APP.BENEFICIARIES(BENEFICIARY_ID),
  INITIATED_AT TIMESTAMP NOT NULL, AMOUNT NUMBER(16,2) NOT NULL, CURRENCY_CODE CHAR(3) NOT NULL,
  REFERENCE_NO VARCHAR2(32) NOT NULL UNIQUE, STATUS VARCHAR2(16) NOT NULL
);
CREATE TABLE ACCOUNT_APP.STATEMENTS (
  STATEMENT_ID NUMBER PRIMARY KEY, ACCOUNT_ID NUMBER NOT NULL REFERENCES ACCOUNT_APP.ACCOUNTS(ACCOUNT_ID),
  PERIOD_START DATE NOT NULL, PERIOD_END DATE NOT NULL, OPENING_BALANCE NUMBER(16,2) NOT NULL,
  CLOSING_BALANCE NUMBER(16,2) NOT NULL, GENERATED_AT TIMESTAMP NOT NULL,
  CONSTRAINT UQ_ACCOUNT_STATEMENT_PERIOD UNIQUE (ACCOUNT_ID, PERIOD_START, PERIOD_END)
);

