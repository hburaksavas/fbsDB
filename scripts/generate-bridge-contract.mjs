import { readFile, writeFile, mkdir } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const schema = JSON.parse(await readFile(new URL('contracts/native-bridge.json', root), 'utf8'));
const check = process.argv.includes('--check');
const pascal = name => name.replace(/(^|[._-])(\w)/g, (_, __, c) => c.toUpperCase());
function tsType(shape) {
  if (shape.$ref) return pascal(shape.$ref);
  if (Array.isArray(shape.type)) return shape.type.map(type => tsType({ ...shape, type })).join(' | ');
  if (shape.type === 'null') return 'null';
  if (shape.type === 'object') return shape.properties ? tsObject(shape) : 'Record<string, JsonValue>';
  if (shape.type === 'array') return `Array<${shape.items ? tsType(shape.items) : 'JsonValue'}>`;
  if (shape.type === 'integer') return 'number';
  return shape.type || 'JsonValue';
}
function tsObject(shape) {
  return '{\n' + Object.entries(shape.properties || {}).map(([key, value]) =>
    `  ${JSON.stringify(key)}${shape.required?.includes(key) ? '' : '?'}: ${tsType(value)};`).join('\n') + '\n}';
}
function csType(shape, optional) {
  const nullable = optional || Array.isArray(shape.type) && shape.type.includes('null');
  const type = Array.isArray(shape.type) ? shape.type.find(type => type !== 'null') : shape.type;
  const result = shape.$ref ? `Bridge${pascal(shape.$ref)}` :
    type === 'string' ? 'string' : type === 'integer' ? 'int' : type === 'number' ? 'double' : type === 'boolean' ? 'bool' :
      type === 'array' ? `${csType(shape.items || {}, false)}[]` : 'JsonElement';
  return result + (nullable ? '?' : '');
}
function record(name, shape, replyType) {
  const fields = Object.entries(shape.properties || {}).map(([key, value]) => {
    const required = shape.required?.includes(key);
    return `    [JsonPropertyName(${JSON.stringify(key)})]\n    public ${required ? 'required ' : ''}${csType(value, !required)} ${pascal(key)} { get; init; }`;
  });
  if (replyType) fields.unshift(`    [JsonPropertyName("type")]\n    public string Type => ${JSON.stringify(replyType)};`);
  return `public sealed record ${name}\n{\n${fields.join('\n')}\n}\n`;
}
const banner = '// Generated by scripts/generate-bridge-contract.mjs. Edit contracts/native-bridge.json.\n';
let ts = banner + 'export type JsonValue = null | boolean | number | string | JsonValue[] | { [key: string]: JsonValue };\n';
for (const [name, shape] of Object.entries(schema.models)) ts += `export type ${pascal(name)} = ${tsObject(shape)};\n`;
ts += 'export interface CommandPayloads {\n' + Object.entries(schema.commands).map(([name, entry]) =>
  `  ${JSON.stringify(name)}: ${tsObject(entry.payload)};`).join('\n') + '\n}\n';
ts += 'export interface ReplyMessages {\n' + Object.entries(schema.replies).map(([name, shape]) =>
  `  ${JSON.stringify(name)}: { type: ${JSON.stringify(name)} } & ${tsObject(shape)};`).join('\n') + '\n}\n';
ts += `export type NativeCommandName = keyof CommandPayloads;
export type NativeCommand<C extends NativeCommandName = NativeCommandName> = C extends NativeCommandName ? { type: 'command'; id: string; command: C; tabId: string; payload: CommandPayloads[C] } : never;
export type NativeReply = ReplyMessages[keyof ReplyMessages];
export type SendNativeCommand = <C extends NativeCommandName>(command: C, ...args: {} extends CommandPayloads[C] ? [payload?: CommandPayloads[C]] : [payload: CommandPayloads[C]]) => string | null;
export interface WireSchema { type?: string | string[]; $ref?: string; properties?: Record<string, WireSchema>; required?: string[]; items?: WireSchema; minimum?: number; maximum?: number; }
export declare const bridgeContract: { version: number; models: Record<string, WireSchema>; commands: Record<NativeCommandName, { handler: 'file' | 'workspace' | 'oracle' | 'ui'; resumeSession: boolean; payload: WireSchema }>; replies: Record<keyof ReplyMessages, WireSchema> };
`;
let cs = banner + '#nullable enable\nusing System.Text.Json;\nusing System.Text.Json.Serialization;\n\nnamespace FbsDb.Bridge;\n\n';
cs += `public static partial class NativeBridgeContract\n{\n    private const string SchemaJson = """\n${JSON.stringify(schema)}\n""";\n}\n\n`;
for (const [name, shape] of Object.entries(schema.models)) cs += record(`Bridge${pascal(name)}`, shape);
for (const [name, entry] of Object.entries(schema.commands)) cs += record(`${pascal(name)}Payload`, entry.payload);
for (const [name, shape] of Object.entries(schema.replies)) cs += record(`${pascal(name)}Reply`, shape, name);
const outputs = {
  'src/bridge/contract.generated.js': banner + `export const bridgeContract = ${JSON.stringify(schema, null, 2)};\n`,
  'src/bridge/contract.generated.d.ts': ts,
  'native/FbsDb/Bridge/NativeBridgeContract.g.cs': cs,
};
for (const [path, contents] of Object.entries(outputs)) {
  const url = new URL(path, root);
  if (check) {
    if (await readFile(url, 'utf8').catch(() => '') !== contents) throw new Error(`Stale bridge contract: ${path}`);
  } else {
    await mkdir(new URL('./', url), { recursive: true });
    await writeFile(url, contents);
  }
}
