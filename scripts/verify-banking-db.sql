SET HEADING ON
SET FEEDBACK ON
SET PAGESIZE 100
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
SELECT SYS_CONTEXT('USERENV', 'SERVICE_NAME') AS SERVICE_NAME,
       SYS_CONTEXT('USERENV', 'SESSION_USER') AS SESSION_USER
FROM DUAL;
SELECT OWNER, COUNT(*) AS TABLE_COUNT
FROM ALL_TABLES
WHERE OWNER IN ('CUSTOMER_APP', 'ACCOUNT_APP', 'LOAN_APP', 'INDEMNITY_APP')
GROUP BY OWNER
ORDER BY OWNER;
SELECT OWNER, COUNT(*) AS FOREIGN_KEY_COUNT
FROM ALL_CONSTRAINTS
WHERE OWNER IN ('CUSTOMER_APP', 'ACCOUNT_APP', 'LOAN_APP', 'INDEMNITY_APP')
  AND CONSTRAINT_TYPE = 'R'
GROUP BY OWNER
ORDER BY OWNER;
SELECT 'CUSTOMERS' AS SAMPLE_SET, COUNT(*) AS ROW_COUNT FROM CUSTOMER_APP.CUSTOMERS
UNION ALL SELECT 'ACCOUNTS', COUNT(*) FROM ACCOUNT_APP.ACCOUNTS
UNION ALL SELECT 'LOANS', COUNT(*) FROM LOAN_APP.LOANS
UNION ALL SELECT 'INDEMNITY CASES', COUNT(*) FROM INDEMNITY_APP.INDEMNITY_CASES
UNION ALL SELECT 'INDEMNITY CREDITS', COUNT(*) FROM INDEMNITY_APP.INDEMNITY_CREDITS
UNION ALL SELECT 'COLLECTION ATTEMPTS', COUNT(*) FROM INDEMNITY_APP.COLLECTION_ATTEMPTS;
SELECT CASE_NO, CREDITOR_NAME, CLAIMED_AMOUNT, INDEMNIFIED_AMOUNT, SETTLED_AMOUNT
FROM INDEMNITY_APP.V_CASE_SETTLEMENT_SUMMARY
ORDER BY CASE_ID;
SELECT CREDIT_NO, ORIGINAL_PRINCIPAL, PRINCIPAL_COLLECTED, REMAINING_PRINCIPAL
FROM INDEMNITY_APP.V_CREDIT_RECOVERY_SUMMARY
ORDER BY CREDIT_ID;
SELECT COUNT(*) AS COLUMN_COUNT, COUNT(c.COMMENTS) AS COMMENTED_COLUMN_COUNT
FROM ALL_TAB_COLUMNS x
LEFT JOIN ALL_COL_COMMENTS c ON c.OWNER=x.OWNER AND c.TABLE_NAME=x.TABLE_NAME AND c.COLUMN_NAME=x.COLUMN_NAME
WHERE x.OWNER='INDEMNITY_APP';
DECLARE
  v_column_count NUMBER;
  v_commented_count NUMBER;
BEGIN
  SELECT COUNT(*), COUNT(c.COMMENTS)
    INTO v_column_count, v_commented_count
  FROM ALL_TAB_COLUMNS x
  LEFT JOIN ALL_COL_COMMENTS c ON c.OWNER=x.OWNER AND c.TABLE_NAME=x.TABLE_NAME AND c.COLUMN_NAME=x.COLUMN_NAME
  WHERE x.OWNER='INDEMNITY_APP';

  IF v_column_count = 0 OR v_column_count <> v_commented_count THEN
    RAISE_APPLICATION_ERROR(-20001, 'Indemnity column comments are incomplete.');
  END IF;
END;
/
EXIT SUCCESS
