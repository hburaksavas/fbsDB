-- Creates three connected sample schemas inside the BANKING_DB PDB.
-- Run after create-banking-pdb.sql, as SYSDBA. The password is requested and not stored here.
SET ECHO OFF
SET VERIFY OFF
SET FEEDBACK ON
SET SERVEROUTPUT ON
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
ACCEPT demo_password CHAR PROMPT 'Demo password for BANKING_DB schemas: ' HIDE

ALTER SESSION SET CONTAINER = BANKING_DB;

CREATE TABLESPACE BANKING_DATA DATAFILE 'D:\ORACLEFREE26AI\ORADATA\FREE\BANKING_DB\banking_data01.dbf' SIZE 64M AUTOEXTEND ON NEXT 16M MAXSIZE 512M;
CREATE USER CUSTOMER_APP IDENTIFIED BY "&demo_password" DEFAULT TABLESPACE BANKING_DATA QUOTA 256M ON BANKING_DATA;
CREATE USER ACCOUNT_APP IDENTIFIED BY "&demo_password" DEFAULT TABLESPACE BANKING_DATA QUOTA 256M ON BANKING_DATA;
CREATE USER LOAN_APP IDENTIFIED BY "&demo_password" DEFAULT TABLESPACE BANKING_DATA QUOTA 256M ON BANKING_DATA;
GRANT CREATE SESSION, CREATE TABLE, CREATE VIEW, CREATE SEQUENCE, CREATE PROCEDURE TO CUSTOMER_APP;
GRANT CREATE SESSION, CREATE TABLE, CREATE VIEW, CREATE SEQUENCE, CREATE PROCEDURE TO ACCOUNT_APP;
GRANT CREATE SESSION, CREATE TABLE, CREATE VIEW, CREATE SEQUENCE, CREATE PROCEDURE TO LOAN_APP;

-- CUSTOMER_APP: customer identity, contact, compliance, consent and segmentation.
CREATE TABLE CUSTOMER_APP.CUSTOMER_TYPES (
  TYPE_ID NUMBER PRIMARY KEY, CODE VARCHAR2(24) NOT NULL UNIQUE, NAME VARCHAR2(80) NOT NULL
);
CREATE TABLE CUSTOMER_APP.CUSTOMERS (
  CUSTOMER_ID NUMBER PRIMARY KEY, CUSTOMER_NO VARCHAR2(20) NOT NULL UNIQUE,
  TYPE_ID NUMBER NOT NULL REFERENCES CUSTOMER_APP.CUSTOMER_TYPES(TYPE_ID),
  NATIONAL_ID VARCHAR2(24) UNIQUE, FIRST_NAME VARCHAR2(60) NOT NULL, LAST_NAME VARCHAR2(60) NOT NULL,
  DATE_OF_BIRTH DATE, EMAIL VARCHAR2(120), PHONE VARCHAR2(30), STATUS VARCHAR2(16) DEFAULT 'ACTIVE' NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE TABLE CUSTOMER_APP.CUSTOMER_ADDRESSES (
  ADDRESS_ID NUMBER PRIMARY KEY, CUSTOMER_ID NUMBER NOT NULL REFERENCES CUSTOMER_APP.CUSTOMERS(CUSTOMER_ID),
  ADDRESS_TYPE VARCHAR2(20) NOT NULL, LINE_1 VARCHAR2(160) NOT NULL, CITY VARCHAR2(60) NOT NULL,
  REGION VARCHAR2(60), POSTAL_CODE VARCHAR2(16), COUNTRY_CODE CHAR(2) DEFAULT 'TR' NOT NULL, IS_PRIMARY CHAR(1) DEFAULT 'N' NOT NULL
);
CREATE TABLE CUSTOMER_APP.CUSTOMER_CONTACTS (
  CONTACT_ID NUMBER PRIMARY KEY, CUSTOMER_ID NUMBER NOT NULL REFERENCES CUSTOMER_APP.CUSTOMERS(CUSTOMER_ID),
  CONTACT_TYPE VARCHAR2(20) NOT NULL, CONTACT_VALUE VARCHAR2(160) NOT NULL, VERIFIED_AT TIMESTAMP, IS_PRIMARY CHAR(1) DEFAULT 'N' NOT NULL
);
CREATE TABLE CUSTOMER_APP.CUSTOMER_EMPLOYMENTS (
  EMPLOYMENT_ID NUMBER PRIMARY KEY, CUSTOMER_ID NUMBER NOT NULL REFERENCES CUSTOMER_APP.CUSTOMERS(CUSTOMER_ID),
  EMPLOYER VARCHAR2(120) NOT NULL, JOB_TITLE VARCHAR2(80), MONTHLY_INCOME NUMBER(14,2), START_DATE DATE NOT NULL, END_DATE DATE
);
CREATE TABLE CUSTOMER_APP.CUSTOMER_KYC (
  KYC_ID NUMBER PRIMARY KEY, CUSTOMER_ID NUMBER NOT NULL UNIQUE REFERENCES CUSTOMER_APP.CUSTOMERS(CUSTOMER_ID),
  STATUS VARCHAR2(20) NOT NULL, RISK_LEVEL VARCHAR2(16) NOT NULL, REVIEWED_AT DATE, REVIEWED_BY VARCHAR2(60)
);
CREATE TABLE CUSTOMER_APP.CUSTOMER_DOCUMENTS (
  DOCUMENT_ID NUMBER PRIMARY KEY, CUSTOMER_ID NUMBER NOT NULL REFERENCES CUSTOMER_APP.CUSTOMERS(CUSTOMER_ID),
  DOCUMENT_TYPE VARCHAR2(32) NOT NULL, DOCUMENT_REF VARCHAR2(80) NOT NULL UNIQUE, ISSUED_AT DATE, EXPIRES_AT DATE, STATUS VARCHAR2(16) NOT NULL
);
CREATE TABLE CUSTOMER_APP.CUSTOMER_CONSENTS (
  CONSENT_ID NUMBER PRIMARY KEY, CUSTOMER_ID NUMBER NOT NULL REFERENCES CUSTOMER_APP.CUSTOMERS(CUSTOMER_ID),
  PURPOSE VARCHAR2(48) NOT NULL, GRANTED CHAR(1) NOT NULL, CAPTURED_AT TIMESTAMP NOT NULL
);
CREATE TABLE CUSTOMER_APP.CUSTOMER_SEGMENTS (
  SEGMENT_ID NUMBER PRIMARY KEY, CODE VARCHAR2(24) NOT NULL UNIQUE, NAME VARCHAR2(80) NOT NULL
);
CREATE TABLE CUSTOMER_APP.CUSTOMER_SEGMENT_MEMBERSHIPS (
  CUSTOMER_ID NUMBER NOT NULL REFERENCES CUSTOMER_APP.CUSTOMERS(CUSTOMER_ID),
  SEGMENT_ID NUMBER NOT NULL REFERENCES CUSTOMER_APP.CUSTOMER_SEGMENTS(SEGMENT_ID), ADDED_AT DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT PK_CUST_SEGMENT_MEMBERS PRIMARY KEY (CUSTOMER_ID, SEGMENT_ID)
);
CREATE TABLE CUSTOMER_APP.CUSTOMER_RELATIONSHIPS (
  RELATIONSHIP_ID NUMBER PRIMARY KEY, CUSTOMER_ID NUMBER NOT NULL REFERENCES CUSTOMER_APP.CUSTOMERS(CUSTOMER_ID),
  RELATED_CUSTOMER_ID NUMBER NOT NULL REFERENCES CUSTOMER_APP.CUSTOMERS(CUSTOMER_ID), RELATIONSHIP_TYPE VARCHAR2(24) NOT NULL,
  CONSTRAINT CK_CUSTOMER_REL_NOT_SELF CHECK (CUSTOMER_ID <> RELATED_CUSTOMER_ID)
);
CREATE TABLE CUSTOMER_APP.CUSTOMER_RISK_PROFILES (
  RISK_PROFILE_ID NUMBER PRIMARY KEY, CUSTOMER_ID NUMBER NOT NULL UNIQUE REFERENCES CUSTOMER_APP.CUSTOMERS(CUSTOMER_ID),
  SCORE NUMBER(3) NOT NULL, RISK_LEVEL VARCHAR2(16) NOT NULL, AS_OF_DATE DATE NOT NULL, MODEL_VERSION VARCHAR2(20) NOT NULL
);

