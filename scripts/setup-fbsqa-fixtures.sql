-- Privileges and objects the live regression needs from another owner. Local BANKING_DB test database only.
-- FBSQA_GRANTS has no password and cannot log in. Removed by remove-fbsqa-fixtures.sql.
WHENEVER SQLERROR EXIT FAILURE
SET SERVEROUTPUT ON FEEDBACK OFF
ALTER SESSION SET CONTAINER = BANKING_DB;

DECLARE
  tablespace_name VARCHAR2(128);
  found NUMBER;
BEGIN
  SELECT MAX(default_tablespace) INTO tablespace_name FROM dba_users WHERE username = 'FBSQA';
  IF tablespace_name IS NULL THEN RAISE_APPLICATION_ERROR(-20001, 'The test user FBSQA does not exist in BANKING_DB.'); END IF;
  SELECT COUNT(*) INTO found FROM dba_users WHERE username = 'FBSQA_GRANTS';
  IF found > 0 THEN EXECUTE IMMEDIATE 'DROP USER FBSQA_GRANTS CASCADE'; END IF;
  SELECT COUNT(*) INTO found FROM dba_roles WHERE role = 'FBSQA_TEST_ROLE';
  IF found > 0 THEN EXECUTE IMMEDIATE 'DROP ROLE FBSQA_TEST_ROLE'; END IF;
  EXECUTE IMMEDIATE 'CREATE USER FBSQA_GRANTS NO AUTHENTICATION DEFAULT TABLESPACE ' || DBMS_ASSERT.SIMPLE_SQL_NAME(tablespace_name) || ' QUOTA 10M ON ' || DBMS_ASSERT.SIMPLE_SQL_NAME(tablespace_name);
END;
/

-- Single column grants: UPDATE only on OPEN_COL, INSERT only on ID and INS_COL, no DELETE.
CREATE TABLE FBSQA_GRANTS.COLUMN_GRANTED (ID NUMBER(10) PRIMARY KEY, OPEN_COL VARCHAR2(40), CLOSED_COL VARCHAR2(40), INS_COL VARCHAR2(40));
INSERT INTO FBSQA_GRANTS.COLUMN_GRANTED VALUES (1, 'open', 'closed', 'ins');
GRANT SELECT ON FBSQA_GRANTS.COLUMN_GRANTED TO FBSQA;
GRANT UPDATE (OPEN_COL) ON FBSQA_GRANTS.COLUMN_GRANTED TO FBSQA;
GRANT INSERT (ID, INS_COL) ON FBSQA_GRANTS.COLUMN_GRANTED TO FBSQA;

-- A grant that only reaches the user through an enabled role.
CREATE TABLE FBSQA_GRANTS.ROLE_GRANTED (ID NUMBER(10) PRIMARY KEY, NOTE VARCHAR2(40));
CREATE ROLE FBSQA_TEST_ROLE;
GRANT SELECT, UPDATE ON FBSQA_GRANTS.ROLE_GRANTED TO FBSQA_TEST_ROLE;
GRANT FBSQA_TEST_ROLE TO FBSQA;

-- INSERT without SELECT: the changed row cannot be read back.
CREATE TABLE FBSQA_GRANTS.INSERT_ONLY (ID NUMBER(10) PRIMARY KEY);
GRANT INSERT ON FBSQA_GRANTS.INSERT_ONLY TO FBSQA;
COMMIT;

-- Lets the suite create identity columns, triggers and views in its own schema.
GRANT CREATE SEQUENCE, CREATE TRIGGER, CREATE VIEW TO FBSQA;

-- FI-007: lets the suite debug its own PL/SQL with DBMS_DEBUG.
GRANT DEBUG CONNECT SESSION TO FBSQA;
EXIT
