using System.Text.RegularExpressions;

namespace FbsDb.Services;

// Grid edits may only run the three DML shapes the grid generates: one statement, quoted identifiers, values as binds.
public static class GridDmlGuard
{
    private static readonly Regex Shape = new(@"^(?:UPDATE\s+(?:""[^""]+""\.)?""[^""]+""\s+SET\s|DELETE\s+FROM\s+(?:""[^""]+""\.)?""[^""]+""\s+WHERE\s|INSERT\s+INTO\s+(?:""[^""]+""\.)?""[^""]+""\s*\()", RegexOptions.IgnoreCase | RegexOptions.Compiled);
    public const int MaxStatements = 500;

    public static void Assert(string sql)
    {
        if (string.IsNullOrWhiteSpace(sql) || sql.Length > 8000) throw new InvalidOperationException("The statement is empty or too long.");
        if (sql.Contains(';') || sql.Contains("--") || sql.Contains("/*")) throw new InvalidOperationException("Only a single statement without comments can be applied.");
        if (!Shape.IsMatch(sql.TrimStart())) throw new InvalidOperationException("Only the INSERT, UPDATE and DELETE statements generated by the grid can be applied.");
    }
}
