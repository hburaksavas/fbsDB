-- BANKING_DB içindeki tazmin ve tahsilat şemasını oluşturur.
-- SYSDBA yetkisiyle çalıştırın. Şema parolası çalıştırma sırasında istenir.
SET ECHO OFF
SET VERIFY OFF
SET FEEDBACK ON
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
ACCEPT demo_password CHAR PROMPT 'Password for INDEMNITY_APP: ' HIDE

ALTER SESSION SET CONTAINER = BANKING_DB;

CREATE USER INDEMNITY_APP IDENTIFIED BY "&demo_password" DEFAULT TABLESPACE BANKING_DATA QUOTA 256M ON BANKING_DATA;
GRANT CREATE SESSION, CREATE TABLE, CREATE VIEW, CREATE SEQUENCE, CREATE PROCEDURE TO INDEMNITY_APP;
GRANT SELECT, REFERENCES ON CUSTOMER_APP.CUSTOMERS TO INDEMNITY_APP;
GRANT SELECT, REFERENCES ON ACCOUNT_APP.ACCOUNTS TO INDEMNITY_APP;

-- Kod tabloları, süreç durumlarını ve tahsilat sözlüğünü tanımlar.
CREATE TABLE INDEMNITY_APP.INDEMNITY_TYPES (
  INDEMNITY_TYPE_ID NUMBER PRIMARY KEY, CODE VARCHAR2(24) NOT NULL UNIQUE, NAME VARCHAR2(80) NOT NULL, IS_ACTIVE CHAR(1) DEFAULT 'Y' NOT NULL
);
CREATE TABLE INDEMNITY_APP.CASE_STATUSES (
  CASE_STATUS_ID NUMBER PRIMARY KEY, CODE VARCHAR2(24) NOT NULL UNIQUE, NAME VARCHAR2(80) NOT NULL, IS_FINAL CHAR(1) DEFAULT 'N' NOT NULL
);
CREATE TABLE INDEMNITY_APP.CREDIT_STATUSES (
  CREDIT_STATUS_ID NUMBER PRIMARY KEY, CODE VARCHAR2(24) NOT NULL UNIQUE, NAME VARCHAR2(80) NOT NULL, IS_FINAL CHAR(1) DEFAULT 'N' NOT NULL
);
CREATE TABLE INDEMNITY_APP.COLLECTION_STATUSES (
  COLLECTION_STATUS_ID NUMBER PRIMARY KEY, CODE VARCHAR2(24) NOT NULL UNIQUE, NAME VARCHAR2(80) NOT NULL, IS_FINAL CHAR(1) DEFAULT 'N' NOT NULL
);
CREATE TABLE INDEMNITY_APP.COLLECTION_CHANNELS (
  COLLECTION_CHANNEL_ID NUMBER PRIMARY KEY, CODE VARCHAR2(24) NOT NULL UNIQUE, NAME VARCHAR2(80) NOT NULL
);
CREATE TABLE INDEMNITY_APP.COLLECTION_OUTCOMES (
  COLLECTION_OUTCOME_ID NUMBER PRIMARY KEY, CODE VARCHAR2(24) NOT NULL UNIQUE, NAME VARCHAR2(80) NOT NULL, REQUIRES_FOLLOW_UP CHAR(1) DEFAULT 'N' NOT NULL
);
CREATE TABLE INDEMNITY_APP.PAYMENT_METHODS (
  PAYMENT_METHOD_ID NUMBER PRIMARY KEY, CODE VARCHAR2(24) NOT NULL UNIQUE, NAME VARCHAR2(80) NOT NULL
);
CREATE TABLE INDEMNITY_APP.LEGAL_STATUSES (
  LEGAL_STATUS_ID NUMBER PRIMARY KEY, CODE VARCHAR2(24) NOT NULL UNIQUE, NAME VARCHAR2(80) NOT NULL, IS_FINAL CHAR(1) DEFAULT 'N' NOT NULL
);

-- Tazmin dosyası, kefalet/garanti borcunun bankaca ödenmesi öncesindeki ve sonrasındaki ana kayıttır.
CREATE TABLE INDEMNITY_APP.INDEMNITY_CASES (
  CASE_ID NUMBER PRIMARY KEY, CASE_NO VARCHAR2(30) NOT NULL UNIQUE,
  CUSTOMER_ID NUMBER NOT NULL REFERENCES CUSTOMER_APP.CUSTOMERS(CUSTOMER_ID),
  INDEMNITY_TYPE_ID NUMBER NOT NULL REFERENCES INDEMNITY_APP.INDEMNITY_TYPES(INDEMNITY_TYPE_ID),
  CASE_STATUS_ID NUMBER NOT NULL REFERENCES INDEMNITY_APP.CASE_STATUSES(CASE_STATUS_ID),
  CREDITOR_NAME VARCHAR2(160) NOT NULL, SOURCE_CONTRACT_NO VARCHAR2(60), CURRENCY_CODE CHAR(3) NOT NULL,
  ORIGINAL_DEBT_AMOUNT NUMBER(18,2) NOT NULL, CLAIMED_AMOUNT NUMBER(18,2) NOT NULL,
  INDEMNIFIED_AMOUNT NUMBER(18,2) DEFAULT 0 NOT NULL, CLAIM_RECEIVED_AT DATE NOT NULL,
  INDEMNIFIED_AT DATE, DESCRIPTION VARCHAR2(500), CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT CK_INDEMNITY_CASE_AMOUNTS CHECK (ORIGINAL_DEBT_AMOUNT >= 0 AND CLAIMED_AMOUNT >= 0 AND INDEMNIFIED_AMOUNT >= 0)
);
CREATE TABLE INDEMNITY_APP.INDEMNITY_SETTLEMENTS (
  SETTLEMENT_ID NUMBER PRIMARY KEY, CASE_ID NUMBER NOT NULL REFERENCES INDEMNITY_APP.INDEMNITY_CASES(CASE_ID),
  SETTLEMENT_REF VARCHAR2(40) NOT NULL UNIQUE, PAID_AT DATE NOT NULL, AMOUNT NUMBER(18,2) NOT NULL,
  CURRENCY_CODE CHAR(3) NOT NULL, PAYEE_NAME VARCHAR2(160) NOT NULL, PAYMENT_METHOD_ID NUMBER NOT NULL REFERENCES INDEMNITY_APP.PAYMENT_METHODS(PAYMENT_METHOD_ID),
  BANK_REFERENCE VARCHAR2(80), NOTES VARCHAR2(300), CONSTRAINT CK_INDEMNITY_SETTLEMENT_AMOUNT CHECK (AMOUNT > 0)
);
CREATE TABLE INDEMNITY_APP.INDEMNITY_CASE_HISTORY (
  CASE_HISTORY_ID NUMBER PRIMARY KEY, CASE_ID NUMBER NOT NULL REFERENCES INDEMNITY_APP.INDEMNITY_CASES(CASE_ID),
  OLD_CASE_STATUS_ID NUMBER REFERENCES INDEMNITY_APP.CASE_STATUSES(CASE_STATUS_ID),
  NEW_CASE_STATUS_ID NUMBER NOT NULL REFERENCES INDEMNITY_APP.CASE_STATUSES(CASE_STATUS_ID),
  CHANGED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL, CHANGED_BY VARCHAR2(80), CHANGE_NOTE VARCHAR2(300)
);
CREATE TABLE INDEMNITY_APP.INDEMNITY_DOCUMENTS (
  DOCUMENT_ID NUMBER PRIMARY KEY, CASE_ID NUMBER NOT NULL REFERENCES INDEMNITY_APP.INDEMNITY_CASES(CASE_ID),
  DOCUMENT_TYPE VARCHAR2(32) NOT NULL, DOCUMENT_REF VARCHAR2(100) NOT NULL UNIQUE,
  RECEIVED_AT DATE, EXPIRES_AT DATE, DOCUMENT_STATUS VARCHAR2(20) DEFAULT 'RECEIVED' NOT NULL, NOTES VARCHAR2(300)
);

-- Tazmin tutarı, müşteriye açılan ayrı bir geri ödeme kredisine dönüştürülür.
CREATE TABLE INDEMNITY_APP.INDEMNITY_CREDITS (
  CREDIT_ID NUMBER PRIMARY KEY, CREDIT_NO VARCHAR2(30) NOT NULL UNIQUE,
  CASE_ID NUMBER NOT NULL UNIQUE REFERENCES INDEMNITY_APP.INDEMNITY_CASES(CASE_ID),
  CUSTOMER_ID NUMBER NOT NULL REFERENCES CUSTOMER_APP.CUSTOMERS(CUSTOMER_ID),
  COLLECTION_ACCOUNT_ID NUMBER REFERENCES ACCOUNT_APP.ACCOUNTS(ACCOUNT_ID),
  CREDIT_STATUS_ID NUMBER NOT NULL REFERENCES INDEMNITY_APP.CREDIT_STATUSES(CREDIT_STATUS_ID),
  CURRENCY_CODE CHAR(3) NOT NULL, ORIGINAL_PRINCIPAL NUMBER(18,2) NOT NULL,
  ANNUAL_RATE NUMBER(9,5) NOT NULL, TERM_MONTHS NUMBER(4) NOT NULL,
  OPENED_AT DATE NOT NULL, FIRST_DUE_AT DATE NOT NULL, MATURITY_AT DATE NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL, CONSTRAINT CK_INDEMNITY_CREDIT_AMOUNTS CHECK (ORIGINAL_PRINCIPAL > 0 AND ANNUAL_RATE >= 0 AND TERM_MONTHS > 0)
);
CREATE TABLE INDEMNITY_APP.CREDIT_RATE_HISTORY (
  RATE_HISTORY_ID NUMBER PRIMARY KEY, CREDIT_ID NUMBER NOT NULL REFERENCES INDEMNITY_APP.INDEMNITY_CREDITS(CREDIT_ID),
  ANNUAL_RATE NUMBER(9,5) NOT NULL, EFFECTIVE_FROM DATE NOT NULL, EFFECTIVE_TO DATE,
  CHANGE_REASON VARCHAR2(160) NOT NULL, APPROVED_BY VARCHAR2(80), CONSTRAINT CK_INDEMNITY_RATE CHECK (ANNUAL_RATE >= 0)
);
CREATE TABLE INDEMNITY_APP.CREDIT_SCHEDULES (
  SCHEDULE_ID NUMBER PRIMARY KEY, CREDIT_ID NUMBER NOT NULL REFERENCES INDEMNITY_APP.INDEMNITY_CREDITS(CREDIT_ID),
  VERSION_NO NUMBER(4) NOT NULL, GENERATED_AT DATE NOT NULL, SCHEDULE_START DATE NOT NULL,
  SCHEDULE_END DATE NOT NULL, PAYMENT_FREQUENCY VARCHAR2(16) DEFAULT 'MONTHLY' NOT NULL,
  CONSTRAINT UQ_INDEMNITY_SCHEDULE_VERSION UNIQUE (CREDIT_ID, VERSION_NO),
  CONSTRAINT UQ_INDEMNITY_SCHEDULE_CREDIT UNIQUE (SCHEDULE_ID, CREDIT_ID)
);
CREATE TABLE INDEMNITY_APP.CREDIT_INSTALLMENTS (
  INSTALLMENT_ID NUMBER PRIMARY KEY, CREDIT_ID NUMBER NOT NULL, SCHEDULE_ID NUMBER NOT NULL,
  INSTALLMENT_NO NUMBER(4) NOT NULL, DUE_AT DATE NOT NULL, PRINCIPAL_DUE NUMBER(18,2) NOT NULL,
  INTEREST_DUE NUMBER(18,2) NOT NULL, FEES_DUE NUMBER(18,2) DEFAULT 0 NOT NULL,
  PENALTY_DUE NUMBER(18,2) DEFAULT 0 NOT NULL, TOTAL_DUE NUMBER(18,2) NOT NULL,
  INSTALLMENT_STATUS VARCHAR2(20) DEFAULT 'DUE' NOT NULL,
  CONSTRAINT FK_INDEMNITY_INSTALLMENT_SCHEDULE FOREIGN KEY (SCHEDULE_ID, CREDIT_ID) REFERENCES INDEMNITY_APP.CREDIT_SCHEDULES(SCHEDULE_ID, CREDIT_ID),
  CONSTRAINT UQ_INDEMNITY_INSTALLMENT_NO UNIQUE (SCHEDULE_ID, INSTALLMENT_NO),
  CONSTRAINT UQ_INDEMNITY_INSTALLMENT_CREDIT UNIQUE (INSTALLMENT_ID, CREDIT_ID),
  CONSTRAINT CK_INDEMNITY_INSTALLMENT_AMOUNTS CHECK (PRINCIPAL_DUE >= 0 AND INTEREST_DUE >= 0 AND FEES_DUE >= 0 AND PENALTY_DUE >= 0 AND TOTAL_DUE >= 0)
);

-- Tahsilat dosyası, görev devri, arama ve müşterinin ödeme taahhüdünü izler.
CREATE TABLE INDEMNITY_APP.COLLECTION_CASES (
  COLLECTION_CASE_ID NUMBER PRIMARY KEY, COLLECTION_CASE_NO VARCHAR2(30) NOT NULL UNIQUE,
  CREDIT_ID NUMBER NOT NULL UNIQUE REFERENCES INDEMNITY_APP.INDEMNITY_CREDITS(CREDIT_ID),
  COLLECTION_STATUS_ID NUMBER NOT NULL REFERENCES INDEMNITY_APP.COLLECTION_STATUSES(COLLECTION_STATUS_ID),
  PRIORITY_CODE VARCHAR2(12) DEFAULT 'NORMAL' NOT NULL, ASSIGNED_TEAM VARCHAR2(80),
  OPENED_AT DATE NOT NULL, NEXT_ACTION_AT DATE, CLOSED_AT DATE, CASE_NOTE VARCHAR2(300)
);
CREATE TABLE INDEMNITY_APP.COLLECTION_ASSIGNMENTS (
  ASSIGNMENT_ID NUMBER PRIMARY KEY, COLLECTION_CASE_ID NUMBER NOT NULL REFERENCES INDEMNITY_APP.COLLECTION_CASES(COLLECTION_CASE_ID),
  COLLECTOR_ID VARCHAR2(80) NOT NULL, ASSIGNED_AT TIMESTAMP NOT NULL, RELEASED_AT TIMESTAMP,
  ASSIGNED_BY VARCHAR2(80), ASSIGNMENT_NOTE VARCHAR2(200)
);
CREATE TABLE INDEMNITY_APP.COLLECTION_ATTEMPTS (
  ATTEMPT_ID NUMBER PRIMARY KEY, COLLECTION_CASE_ID NUMBER NOT NULL REFERENCES INDEMNITY_APP.COLLECTION_CASES(COLLECTION_CASE_ID),
  COLLECTION_CHANNEL_ID NUMBER NOT NULL REFERENCES INDEMNITY_APP.COLLECTION_CHANNELS(COLLECTION_CHANNEL_ID),
  COLLECTION_OUTCOME_ID NUMBER NOT NULL REFERENCES INDEMNITY_APP.COLLECTION_OUTCOMES(COLLECTION_OUTCOME_ID),
  ATTEMPTED_AT TIMESTAMP NOT NULL, COLLECTOR_ID VARCHAR2(80), CONTACT_NAME VARCHAR2(120),
  AMOUNT_REQUESTED NUMBER(18,2), AMOUNT_RECOVERED NUMBER(18,2) DEFAULT 0 NOT NULL,
  NEXT_ACTION_AT DATE, EXTERNAL_REFERENCE VARCHAR2(80), NOTES VARCHAR2(500),
  CONSTRAINT CK_INDEMNITY_ATTEMPT_AMOUNTS CHECK (NVL(AMOUNT_REQUESTED,0) >= 0 AND AMOUNT_RECOVERED >= 0)
);
CREATE TABLE INDEMNITY_APP.REPAYMENT_PROMISES (
  PROMISE_ID NUMBER PRIMARY KEY, COLLECTION_CASE_ID NUMBER NOT NULL REFERENCES INDEMNITY_APP.COLLECTION_CASES(COLLECTION_CASE_ID),
  ATTEMPT_ID NUMBER REFERENCES INDEMNITY_APP.COLLECTION_ATTEMPTS(ATTEMPT_ID),
  PROMISED_AMOUNT NUMBER(18,2) NOT NULL, PROMISED_FOR DATE NOT NULL, PROMISE_STATUS VARCHAR2(20) DEFAULT 'OPEN' NOT NULL,
  FULFILLED_AMOUNT NUMBER(18,2) DEFAULT 0 NOT NULL, RECORDED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  RESOLVED_AT TIMESTAMP, NOTES VARCHAR2(300), CONSTRAINT CK_INDEMNITY_PROMISE_AMOUNTS CHECK (PROMISED_AMOUNT > 0 AND FULFILLED_AMOUNT >= 0)
);
CREATE TABLE INDEMNITY_APP.COLLECTION_NOTES (
  COLLECTION_NOTE_ID NUMBER PRIMARY KEY, COLLECTION_CASE_ID NUMBER NOT NULL REFERENCES INDEMNITY_APP.COLLECTION_CASES(COLLECTION_CASE_ID),
  NOTE_TYPE VARCHAR2(24) NOT NULL, NOTE_TEXT VARCHAR2(1000) NOT NULL, CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL, CREATED_BY VARCHAR2(80)
);

-- Müşteriden alınan tahsilatı, kredi taksitlerine dağıtılan tutarlardan ayrı tutar.
CREATE TABLE INDEMNITY_APP.CREDIT_RECEIPTS (
  RECEIPT_ID NUMBER PRIMARY KEY, RECEIPT_NO VARCHAR2(32) NOT NULL UNIQUE,
  CREDIT_ID NUMBER NOT NULL REFERENCES INDEMNITY_APP.INDEMNITY_CREDITS(CREDIT_ID),
  COLLECTION_CASE_ID NUMBER REFERENCES INDEMNITY_APP.COLLECTION_CASES(COLLECTION_CASE_ID),
  PAYMENT_METHOD_ID NUMBER NOT NULL REFERENCES INDEMNITY_APP.PAYMENT_METHODS(PAYMENT_METHOD_ID),
  RECEIVED_AT TIMESTAMP NOT NULL, AMOUNT NUMBER(18,2) NOT NULL, CURRENCY_CODE CHAR(3) NOT NULL,
  EXTERNAL_REFERENCE VARCHAR2(100), RECEIPT_STATUS VARCHAR2(20) DEFAULT 'POSTED' NOT NULL,
  CONSTRAINT UQ_INDEMNITY_RECEIPT_CREDIT UNIQUE (RECEIPT_ID, CREDIT_ID), CONSTRAINT CK_INDEMNITY_RECEIPT_AMOUNT CHECK (AMOUNT > 0)
);
CREATE TABLE INDEMNITY_APP.CREDIT_RECEIPT_ALLOCATIONS (
  ALLOCATION_ID NUMBER PRIMARY KEY, RECEIPT_ID NUMBER NOT NULL, CREDIT_ID NUMBER NOT NULL,
  INSTALLMENT_ID NUMBER NOT NULL, PRINCIPAL_AMOUNT NUMBER(18,2) DEFAULT 0 NOT NULL,
  INTEREST_AMOUNT NUMBER(18,2) DEFAULT 0 NOT NULL, FEES_AMOUNT NUMBER(18,2) DEFAULT 0 NOT NULL,
  PENALTY_AMOUNT NUMBER(18,2) DEFAULT 0 NOT NULL, ALLOCATION_AMOUNT NUMBER(18,2) NOT NULL,
  CONSTRAINT FK_INDEMNITY_ALLOCATION_RECEIPT FOREIGN KEY (RECEIPT_ID, CREDIT_ID) REFERENCES INDEMNITY_APP.CREDIT_RECEIPTS(RECEIPT_ID, CREDIT_ID),
  CONSTRAINT FK_INDEMNITY_ALLOCATION_INSTALLMENT FOREIGN KEY (INSTALLMENT_ID, CREDIT_ID) REFERENCES INDEMNITY_APP.CREDIT_INSTALLMENTS(INSTALLMENT_ID, CREDIT_ID),
  CONSTRAINT CK_INDEMNITY_ALLOCATION_AMOUNT CHECK (PRINCIPAL_AMOUNT >= 0 AND INTEREST_AMOUNT >= 0 AND FEES_AMOUNT >= 0 AND PENALTY_AMOUNT >= 0 AND ALLOCATION_AMOUNT = PRINCIPAL_AMOUNT + INTEREST_AMOUNT + FEES_AMOUNT + PENALTY_AMOUNT)
);

-- Gerekirse yasal takip, masraf, düzeltme ve dönemsel bakiye de aynı krediye bağlanır.
CREATE TABLE INDEMNITY_APP.LEGAL_PROCEEDINGS (
  LEGAL_PROCEEDING_ID NUMBER PRIMARY KEY, LEGAL_CASE_NO VARCHAR2(40) NOT NULL UNIQUE,
  COLLECTION_CASE_ID NUMBER NOT NULL REFERENCES INDEMNITY_APP.COLLECTION_CASES(COLLECTION_CASE_ID),
  LEGAL_STATUS_ID NUMBER NOT NULL REFERENCES INDEMNITY_APP.LEGAL_STATUSES(LEGAL_STATUS_ID),
  COURT_NAME VARCHAR2(160), LAW_FIRM VARCHAR2(160), FILED_AT DATE, LAST_EVENT_AT DATE, CLOSED_AT DATE, NOTES VARCHAR2(400)
);
CREATE TABLE INDEMNITY_APP.LEGAL_EVENTS (
  LEGAL_EVENT_ID NUMBER PRIMARY KEY, LEGAL_PROCEEDING_ID NUMBER NOT NULL REFERENCES INDEMNITY_APP.LEGAL_PROCEEDINGS(LEGAL_PROCEEDING_ID),
  EVENT_TYPE VARCHAR2(32) NOT NULL, EVENT_AT DATE NOT NULL, EVENT_REFERENCE VARCHAR2(80), DESCRIPTION VARCHAR2(500), CREATED_BY VARCHAR2(80)
);
CREATE TABLE INDEMNITY_APP.RECOVERY_COSTS (
  RECOVERY_COST_ID NUMBER PRIMARY KEY, CREDIT_ID NUMBER NOT NULL REFERENCES INDEMNITY_APP.INDEMNITY_CREDITS(CREDIT_ID),
  LEGAL_PROCEEDING_ID NUMBER REFERENCES INDEMNITY_APP.LEGAL_PROCEEDINGS(LEGAL_PROCEEDING_ID),
  COST_TYPE VARCHAR2(32) NOT NULL, COST_DATE DATE NOT NULL, AMOUNT NUMBER(18,2) NOT NULL,
  CURRENCY_CODE CHAR(3) NOT NULL, DESCRIPTION VARCHAR2(240), CONSTRAINT CK_INDEMNITY_RECOVERY_COST CHECK (AMOUNT > 0)
);
CREATE TABLE INDEMNITY_APP.CREDIT_ADJUSTMENTS (
  ADJUSTMENT_ID NUMBER PRIMARY KEY, CREDIT_ID NUMBER NOT NULL REFERENCES INDEMNITY_APP.INDEMNITY_CREDITS(CREDIT_ID),
  ADJUSTMENT_TYPE VARCHAR2(32) NOT NULL, ADJUSTMENT_DATE DATE NOT NULL, AMOUNT NUMBER(18,2) NOT NULL,
  REASON VARCHAR2(240) NOT NULL, APPROVED_BY VARCHAR2(80), EXTERNAL_REFERENCE VARCHAR2(80), CONSTRAINT CK_INDEMNITY_ADJUSTMENT CHECK (AMOUNT <> 0)
);
CREATE TABLE INDEMNITY_APP.CREDIT_BALANCE_SNAPSHOTS (
  SNAPSHOT_ID NUMBER PRIMARY KEY, CREDIT_ID NUMBER NOT NULL REFERENCES INDEMNITY_APP.INDEMNITY_CREDITS(CREDIT_ID),
  AS_OF_DATE DATE NOT NULL, PRINCIPAL_BALANCE NUMBER(18,2) NOT NULL, INTEREST_BALANCE NUMBER(18,2) NOT NULL,
  FEES_BALANCE NUMBER(18,2) NOT NULL, PENALTY_BALANCE NUMBER(18,2) NOT NULL,
  TOTAL_BALANCE NUMBER(18,2) NOT NULL, SNAPSHOT_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT UQ_INDEMNITY_CREDIT_SNAPSHOT UNIQUE (CREDIT_ID, AS_OF_DATE),
  CONSTRAINT CK_INDEMNITY_BALANCE_AMOUNTS CHECK (PRINCIPAL_BALANCE >= 0 AND INTEREST_BALANCE >= 0 AND FEES_BALANCE >= 0 AND PENALTY_BALANCE >= 0 AND TOTAL_BALANCE >= 0)
);
CREATE TABLE INDEMNITY_APP.CREDIT_GUARANTORS (
  CREDIT_ID NUMBER NOT NULL REFERENCES INDEMNITY_APP.INDEMNITY_CREDITS(CREDIT_ID),
  CUSTOMER_ID NUMBER NOT NULL REFERENCES CUSTOMER_APP.CUSTOMERS(CUSTOMER_ID),
  GUARANTOR_ROLE VARCHAR2(24) NOT NULL, GUARANTEE_LIMIT NUMBER(18,2), SIGNED_AT DATE NOT NULL,
  GUARANTEE_STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL, CONSTRAINT PK_INDEMNITY_CREDIT_GUARANTORS PRIMARY KEY (CREDIT_ID, CUSTOMER_ID)
);

