CREATE VIEW INDEMNITY_APP.V_CASE_SETTLEMENT_SUMMARY AS
SELECT c.CASE_ID, c.CASE_NO, c.CUSTOMER_ID, c.CREDITOR_NAME, c.CLAIMED_AMOUNT, c.INDEMNIFIED_AMOUNT,
       NVL(SUM(s.AMOUNT),0) AS SETTLED_AMOUNT,
       GREATEST(c.CLAIMED_AMOUNT-NVL(SUM(s.AMOUNT),0),0) AS UNSETTLED_CLAIM_AMOUNT
FROM INDEMNITY_APP.INDEMNITY_CASES c
LEFT JOIN INDEMNITY_APP.INDEMNITY_SETTLEMENTS s ON s.CASE_ID=c.CASE_ID
GROUP BY c.CASE_ID,c.CASE_NO,c.CUSTOMER_ID,c.CREDITOR_NAME,c.CLAIMED_AMOUNT,c.INDEMNIFIED_AMOUNT;
CREATE VIEW INDEMNITY_APP.V_CREDIT_RECOVERY_SUMMARY AS
SELECT c.CREDIT_ID,c.CREDIT_NO,c.CASE_ID,c.CUSTOMER_ID,c.ORIGINAL_PRINCIPAL,
       NVL(SUM(a.PRINCIPAL_AMOUNT),0) AS PRINCIPAL_COLLECTED,
       GREATEST(c.ORIGINAL_PRINCIPAL-NVL(SUM(a.PRINCIPAL_AMOUNT),0),0) AS REMAINING_PRINCIPAL,
       NVL(SUM(a.INTEREST_AMOUNT),0) AS INTEREST_COLLECTED,
       NVL(SUM(a.FEES_AMOUNT),0) AS FEES_COLLECTED,
       NVL(SUM(a.PENALTY_AMOUNT),0) AS PENALTY_COLLECTED,
       MAX(r.RECEIVED_AT) AS LAST_RECEIPT_AT
FROM INDEMNITY_APP.INDEMNITY_CREDITS c
LEFT JOIN INDEMNITY_APP.CREDIT_RECEIPT_ALLOCATIONS a ON a.CREDIT_ID=c.CREDIT_ID
LEFT JOIN INDEMNITY_APP.CREDIT_RECEIPTS r ON r.RECEIPT_ID=a.RECEIPT_ID AND r.CREDIT_ID=a.CREDIT_ID
GROUP BY c.CREDIT_ID,c.CREDIT_NO,c.CASE_ID,c.CUSTOMER_ID,c.ORIGINAL_PRINCIPAL;
COMMENT ON TABLE INDEMNITY_APP.V_CASE_SETTLEMENT_SUMMARY IS 'Tazmin dosyasındaki talep tutarıyla alacaklıya yapılan ödemeleri karşılaştırır.';
COMMENT ON TABLE INDEMNITY_APP.V_CREDIT_RECOVERY_SUMMARY IS 'Tazmin kredisinde tahsil edilmiş anapara ve diğer kalemleri özetler.';

