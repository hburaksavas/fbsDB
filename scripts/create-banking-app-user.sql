SET DEFINE ON
SET SERVEROUTPUT ON
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

DEFINE app_password = &1
ALTER SESSION SET CONTAINER=BANKING_DB;

DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count FROM DBA_USERS WHERE USERNAME='BANKING_APP';
  IF v_count=0 THEN
    EXECUTE IMMEDIATE 'CREATE USER BANKING_APP IDENTIFIED BY "&app_password"';
  ELSE
    EXECUTE IMMEDIATE 'ALTER USER BANKING_APP IDENTIFIED BY "&app_password" ACCOUNT UNLOCK';
  END IF;
  EXECUTE IMMEDIATE 'GRANT CREATE SESSION, CREATE SYNONYM TO BANKING_APP';
END;
/

DECLARE
BEGIN
  FOR t IN (
    SELECT owner, object_name
    FROM DBA_OBJECTS
    WHERE owner IN ('CUSTOMER_APP','ACCOUNT_APP','LOAN_APP','INDEMNITY_APP')
      AND object_type IN ('TABLE','VIEW')
    ORDER BY object_name
  ) LOOP
    EXECUTE IMMEDIATE 'GRANT SELECT ON '||t.owner||'.'||t.object_name||' TO BANKING_APP';
    EXECUTE IMMEDIATE 'CREATE OR REPLACE SYNONYM BANKING_APP.'||t.object_name||' FOR '||t.owner||'.'||t.object_name;
  END LOOP;
END;
/

PROMPT BANKING_APP is ready with read-only access and private synonyms.
SELECT COUNT(*) AS SYNONYM_COUNT FROM DBA_SYNONYMS WHERE OWNER='BANKING_APP';
EXIT SUCCESS
