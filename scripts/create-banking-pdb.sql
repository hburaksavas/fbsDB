-- Creates the BANKING_DB pluggable database from Oracle Free's local PDB seed.
-- Run as SYSDBA from the local Oracle Free installation.
SET ECHO OFF
SET VERIFY OFF
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
ACCEPT demo_password CHAR PROMPT 'Demo password for BANKING_DB administration: ' HIDE
CREATE PLUGGABLE DATABASE BANKING_DB
  ADMIN USER PDBADMIN IDENTIFIED BY "&demo_password"
  FILE_NAME_CONVERT = (
    'D:\ORACLEFREE26AI\ORADATA\FREE\PDBSEED\',
    'D:\ORACLEFREE26AI\ORADATA\FREE\BANKING_DB\'
  );
ALTER PLUGGABLE DATABASE BANKING_DB OPEN;
ALTER PLUGGABLE DATABASE BANKING_DB SAVE STATE;
ALTER SYSTEM REGISTER;
EXIT SUCCESS
